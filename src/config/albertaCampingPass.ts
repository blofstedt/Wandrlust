/**
 * The Public Lands Camping Pass area, as Alberta publishes it.
 *
 * ---------------------------------------------------------------------------
 * WHY THIS IS 224 POINTS AND NOT A RECTANGLE
 * ---------------------------------------------------------------------------
 *
 * `permits.ts` used a bounding box, and a bounding box around this shape is
 * wrong by most of Alberta: the real area is a ragged 66,710 km² strip that
 * follows highways down the Eastern Slopes and takes in the Porcupine Hills
 * PLUZ, and the box around it swallows Edmonton, Red Deer and a great deal of
 * farmland where the pass has nothing to say. Every match had to be hedged
 * into "may apply — check", which is the honest thing to do with a rectangle
 * and a poor answer to give somebody standing in the Ghost.
 *
 * Read once from the province's own layer
 * (`geospatial.alberta.ca/mimas/.../land_public_land_camping_pass_public`),
 * simplified server-side to about 2 km, and committed — the pattern this repo
 * uses for reference data that does not change. The fetch route is
 * `/api/alberta-rec/pass-geometry`; it is a developer tool and nothing calls
 * it at runtime.
 *
 * ABOUT THE TOLERANCE. Simplified to roughly 2 km, so the edge is soft by
 * about that much. That is why a match still says "check the exact boundary
 * with the province" rather than pretending to be the legal line — but it is
 * the difference between hedging about all of Alberta and hedging about a
 * two-kilometre band, and only one of those is useful.
 *
 * The layer also carries a four-point hole about a kilometre across. It is
 * dropped: at this tolerance it is noise, and including it could only ever
 * turn a "you need a pass" into a "you don't", which is the wrong direction
 * to be wrong in.
 *
 * Fetched 2026-08-29.
 */

