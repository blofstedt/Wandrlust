/**
 * Ray casting, on the raw ring.
 *
 * No projection: the ring and the point are both in degrees and the test only
 * asks which side of each edge the point falls, which projection does not
 * change. A point exactly on an edge may go either way and that is fine —
 * the boundary is soft by 2 km already, and the wording says so.
 */
export const insideCampingPassArea = (lat: number, lon: number): boolean => {
  let inside = false;
  const ring = AB_CAMPING_PASS_RING;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    const straddles = (yi > lat) !== (yj > lat);
    if (straddles && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
};
